/* ========================================
   Type Definitions for the Dataset Tool
   ======================================== */

/** A single prediction result from the AI model */
export interface Prediction {
  className: string;
  probability: number;
}

/** Represents a single image in the dataset */
export interface ImageItem {
  id: string;
  file: File;
  name: string;
  size: number;
  sizeFormatted: string;
  label: string;
  preview: string; // base64 data URL
  uploadedAt: Date;
  /** AI classification status */
  classifying: boolean;
  /** All predictions returned by MobileNet */
  predictions: Prediction[];
  /** Whether the label was auto-generated by AI */
  autoLabeled: boolean;
}

/** Available pages/views in the application */
export type PageView =
  | 'landing'
  | 'dashboard'
  | 'upload'
  | 'preview'
  | 'export'
  | 'about'
  | 'statistics';

/** Notification types for toast messages */
export type NotificationType = 'success' | 'error' | 'info' | 'warning';

/** Notification object */
export interface Notification {
  id: string;
  message: string;
  type: NotificationType;
}
